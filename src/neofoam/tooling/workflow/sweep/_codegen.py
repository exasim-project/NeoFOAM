"""Snakefile generation for an exported parameter sweep.

:func:`sweep_snakefile` emits the runnable ``Snakefile``: a thin header (build the
:class:`~neofoam.tooling.workflow.paramspace.YamlParamSpace`, materialize the
per-case/per-variant configs at parse time, define the globals the static ``.smk``
files consume) followed by ``include:`` lines referencing the packaged rule library.

The metadata a reader needs to reconstruct the sweep (solver, base case, enabled
rules) is written separately as a JSON sidecar by
:mod:`neofoam.tooling.workflow.sweep._io` — this module only produces the executable
workflow, never the read-back contract.
"""

from __future__ import annotations

import json
from collections.abc import Sequence
from pathlib import Path

from neofoam.tooling.workflow.rules import (
    MESH_DIM,
    RuleRegistry,
    default_registry,
)


def sweep_snakefile(
    solver_name: str,
    base_case: str | Path,
    dims: Sequence[str],
    *,
    registry: RuleRegistry | None = None,
    enabled: Sequence[str] | None = None,
) -> str:
    """Generate the Snakefile: a thin header + the packaged rule includes.

    The header builds the :class:`~neofoam.tooling.workflow.paramspace.YamlParamSpace`,
    materializes the per-case and per-mesh-variant configs at parse time
    (``write_if_changed`` keeps unchanged cases from re-running) and defines
    the plain globals the static ``.smk`` files consume — Snakemake's
    ``include:`` shares the Snakefile's namespace.
    """
    plan = (registry or default_registry()).plan(enabled)
    base = str(Path(base_case).resolve())
    setup_dims = sorted(d for d in dims if d != MESH_DIM)
    includes = "\n".join(
        f'include: str(rules_dir() / "{spec.smk_file}")'
        for spec in plan.rules
        if spec.smk_file  # `all` is emitted inline below
    )
    # MESH_STEM is the mesh mini-case dir used verbatim as the mesh-chain rules'
    # static `output:` (so it stays a literal wildcard path, never a lambda);
    # _mesh_case / _mesh_dir_of compute the concrete dirs for the
    # input:/params: lambdas.
    mesh_stem_block = (
        'MESH_STEM = "meshes/{mesh}"\n'
        "def _mesh_case(wc):\n"
        '    return f"meshes/{wc.mesh}"\n'
        "def _mesh_dir_of(wc):\n"
        '    return f"meshes/{mesh_axis.of(wc)}"'
    )
    return f'''# Generated by NeoFOAM — parameter sweep composed from the packaged rule
# library (neofoam.tooling.workflow.rules; see the included .smk files for the rule
# bodies). Run from this directory:  snakemake -n  (dry run),  snakemake -j4
# Requires: the neofoam package (pybFoam) importable and snakemake to execute.
from neofoam.tooling.workflow.paramspace import YamlParamSpace
from neofoam.tooling.workflow.rules import rules_dir

SOLVER = {json.dumps(solver_name)}
# The CLI subcommand (`neofoam solver <cmd>`) — the solver name, lowercased.
SOLVER_CMD = {json.dumps(solver_name.lower())}
BASE_CASE = {json.dumps(base)}
SETUP_DIMS = {setup_dims!r}
MESH_TOOL_INPUT = {plan.mesh_tool_input!r}
MESH_DONE = "{plan.mesh_done}"
FINAL_PATTERN = "{plan.final_pattern}"

space = YamlParamSpace("sweep.csv", "params.yaml")
space.materialize({{"setup": SETUP_DIMS}}, out_dir="configs")
mesh_axis = space.keyed("{MESH_DIM}", out_dir="configs")
{mesh_stem_block}
cases = space.cases

{includes}


# The default target lives in the MAIN Snakefile: Snakemake never picks a rule
# from an include:d file as the implicit default target.
rule all:
    input:
        expand(FINAL_PATTERN, case=cases)
'''
