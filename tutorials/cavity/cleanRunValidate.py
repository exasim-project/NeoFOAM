import sys
import subprocess
import shutil
import logging
import argparse
import numpy as np
import time

from pathlib import Path
from foamlib import FoamCase
from typing import Tuple

# =========================================================
#  Logging Setup
# =========================================================
logging.basicConfig(
    format="%(asctime)s %(levelname)s %(message)s",
    level=logging.INFO,
    datefmt="%H:%M:%S",
)
logger = logging.getLogger(__name__)


# =========================================================
#  Utility: Run shell commands
# =========================================================
def run(cmd: list[str], cwd: Path = None) -> None:
    logger.info(f"Running: {' '.join(cmd)}")
    try:
        subprocess.check_call(cmd, cwd=cwd)
    except subprocess.CalledProcessError as e:
        logger.error(f"Command failed: {' '.join(cmd)}")
        sys.exit(e.returncode)


# =========================================================
#  Clean Functionality
# =========================================================
def rm_path(p: Path) -> None:
    if not p.exists():
        return
    try:
        if p.is_dir():
            shutil.rmtree(p)
        else:
            p.unlink()
        logger.info(f"Removed: {p}")
    except Exception as e:
        logger.error(f"Failed to remove {p}: {e}")


def clean_case(case_path: Path) -> None:
    logger.info("Cleaning case (Allclean equivalent)...")
    # Remove time dirs
    for d in case_path.iterdir():
        if d.is_dir():
            try:
                float(d.name)  # test if folder is a time directory
                rm_path(d)
            except ValueError:
                pass
    # Remove processor* dirs
    for d in case_path.glob("processor*"):
        rm_path(d)
    # Remove *.foam
    for f in case_path.glob("*.foam"):
        rm_path(f)
    # Remove log files
    for globpat in ("log.*", "*.log"):
        for f in case_path.glob(globpat):
            rm_path(f)
    # Remove postProcessing
    rm_path(case_path / "postProcessing")
    # Remove mesh generated by blockMesh
    rm_path(case_path / "constant" / "polyMesh")

    logger.info("Allclean complete.")


# =========================================================
#  Allrun Functionality
# =========================================================
def restore0_dir(case_path: Path) -> None:
    zero = case_path / "0"
    zero_orig = case_path / "0.orig"
    rm_path(zero)
    if not zero_orig.exists():
        logger.error("0.orig directory missing.")
        raise RuntimeError("0.orig missing")
    shutil.copytree(zero_orig, zero)
    logger.info("Restored 0/ from 0.orig/")


def run_case(case_path: Path, preset: str = "develop", mode: str = "serial") -> None:
    logger.info("Starting Allrun workflow...")

    foamfile = case_path / "cavity.foam"
    foamfile.touch()
    restore0_dir(case_path)

    blockmesh_log = open(case_path / "log.blockMesh", "w")
    logger.info("Running blockMesh")
    try:
        subprocess.check_call(
            ["blockMesh"], cwd=case_path, stdout=blockmesh_log, stderr=subprocess.STDOUT
        )
    except subprocess.CalledProcessError as e:
        logger.error("blockMesh failed.")
        sys.exit(e.returncode)
    finally:
        blockmesh_log.close()

    if mode == "parallel":
        decompose_log = open(case_path / "log.decomposePar", "w")
        logger.info("Running decomposePar")
        try:
            subprocess.check_call(
                ["decomposePar"],
                cwd=case_path,
                stdout=decompose_log,
                stderr=subprocess.STDOUT,
            )
        except subprocess.CalledProcessError as e:
            logger.error("decomposePar failed.")
            sys.exit(e.returncode)
        finally:
            decompose_log.close()

    solver = case_path / f"../../build/{preset}/bin/neoIcoFoam"
    if not solver.exists():
        logger.error(f"Solver binary not found: {solver}")
        sys.exit(1)

    neo_log = open(case_path / "log.neoIcoFoam", "w")
    logger.info("Running neoIcoFoam")
    try:
        if mode == "parallel":
            run_args = ["mpirun", "-n", "4", str(solver), "-parallel"]
        else:
            run_args = [str(solver)]

        subprocess.check_call(
            run_args, cwd=case_path, stdout=neo_log, stderr=subprocess.STDOUT
        )
    except subprocess.CalledProcessError as e:
        logger.error("neoIcoFoam failed.")
        print(e)
        sys.exit(e.returncode)
    finally:
        neo_log.close()
    if mode == "parallel":
        reconstruct_log = open(case_path / "log.reconstructPar", "w")
        logger.info("Running recontsructPar")
        try:
            subprocess.check_call(
                ["reconstructPar"],
                cwd=case_path,
                stdout=reconstruct_log,
                stderr=subprocess.STDOUT,
            )
        except subprocess.CalledProcessError as e:
            logger.error("reconstructPar failed.")
            sys.exit(e.returncode)
        finally:
            reconstruct_log.close()

    logger.info("Allrun completed.")


# =========================================================
#  Data Extraction
# =========================================================
def computeRe(case: FoamCase) -> Tuple[float, float]:
    tp = case["constant"]["transportProperties"]
    nu = float(tp["nu"])
    Re = 1.0 / nu
    logger.info(f"nu = {nu:.6g}; Computed Re = {Re:.3f}")
    return nu, Re


def detect_latest_time(case_path: Path) -> float:
    times = []
    for d in case_path.iterdir():
        if d.is_dir():
            try:
                times.append(float(d.name))
            except ValueError:
                pass
    if not times:
        raise RuntimeError("No time directories found!")
    return max(times)


def load_ghia_header(filename: Path) -> np.ndarray:
    with open(filename, "r") as f:
        for line in f:
            stripped = line.strip()
            if stripped.startswith("%"):
                parts = stripped.lstrip("%").split()
                nums = [int(p) for p in parts if p.isdigit()]
                if len(nums) >= 2:
                    return np.array(nums)
    raise RuntimeError("Could not extract Re header from Ghia file.")


def select_ghia_column(GHIA_RE_VALUES: np.ndarray, Re: float) -> Tuple[int, int]:
    Re_rounded = GHIA_RE_VALUES[np.argmin(np.abs(GHIA_RE_VALUES - Re))]
    col_index = np.where(GHIA_RE_VALUES == Re_rounded)[0][0] + 1
    logger.info(f"-> Selecting Ghia Re={Re_rounded}, column={col_index}")
    return Re_rounded, col_index


# =========================================================
#  Centreline Extraction
# =========================================================
def extract_centreline(x, y, U_int, line_value, is_vertical=True):
    if is_vertical:
        dist = np.abs(x - line_value)
        unique_vals = np.unique(np.round(y, 5))
        vals, comp = [], []
        for val in unique_vals:
            mask = np.isclose(y, val, atol=5e-3)
            if np.any(mask):
                choices = np.where(mask)[0]
                i = choices[np.argmin(dist[mask])]
                vals.append(y[i])
                comp.append(U_int[i][0])
        idx = np.argsort(vals)
        return np.array(vals)[idx], np.array(comp)[idx]
    else:
        dist = np.abs(y - line_value)
        unique_vals = np.unique(np.round(x, 5))
        vals, comp = [], []
        for val in unique_vals:
            mask = np.isclose(x, val, atol=5e-3)
            if np.any(mask):
                choices = np.where(mask)[0]
                i = choices[np.argmin(dist[mask])]
                vals.append(x[i])
                comp.append(U_int[i][1])
        idx = np.argsort(vals)
        return np.array(vals)[idx], np.array(comp)[idx]


# =========================================================
#  Main
# =========================================================
def main() -> None:
    start_time = time.perf_counter()
    try:
        parser = argparse.ArgumentParser(
            description="Run cavity test + validate results."
        )
        parser.add_argument("--clean", action="store_true", help="Clean case only")
        parser.add_argument("--run", action="store_true", help="Run solver only")
        parser.add_argument("--case", type=str, default=".", help="Case directory")
        parser.add_argument("--mode", type=str, default="serial", help="Case directory")
        parser.add_argument(
            "--preset",
            type=str,
            default="develop",
            help="CMake preset name (used in build/<preset>/bin/)",
        )
        parser.add_argument("--tol-u", type=float, default=5e-2)
        parser.add_argument("--tol-v", type=float, default=5e-2)
        args = parser.parse_args()

        case_path = Path(args.case).resolve()
        logger.info(f"Case path: {case_path}")

        if args.clean and not args.run:
            clean_case(case_path)
            return

        if args.run and not args.clean:
            run_case(case_path, args.preset)
            return

        # Default: clean + run + validate
        clean_case(case_path)
        run_case(case_path, args.preset, args.mode)

        case = FoamCase(case_path)
        nu, Re = computeRe(case)
        endTime = detect_latest_time(case_path)

        t = case[endTime]
        U = t["U"]
        C = t.cell_centers()
        U_int = np.asarray(U.internal_field)
        C_int = np.asarray(C.internal_field)
        x, y = C_int[:, 0], C_int[:, 1]

        ghia_u = np.loadtxt(case_path / "ghia_u.txt", comments="%")
        ghia_v = np.loadtxt(case_path / "ghia_v.txt", comments="%")
        GHIA_Y = ghia_u[:, 0]
        GHIA_X = ghia_v[:, 0]

        GHIA_RE_VALUES = load_ghia_header(case_path / "ghia_u.txt")
        Re_rounded, col_index = select_ghia_column(GHIA_RE_VALUES, Re)
        GHIA_U = ghia_u[:, col_index]
        GHIA_V = ghia_v[:, col_index]

        y_cl, u_cl = extract_centreline(x, y, U_int, 0.5, True)
        x_cl, v_cl = extract_centreline(x, y, U_int, 0.5, False)

        # Add wall boundary values
        y_cl = np.concatenate(([0.0], y_cl, [1.0]))
        u_cl = np.concatenate(([0.0], u_cl, [1.0]))
        x_cl = np.concatenate(([0.0], x_cl, [1.0]))
        v_cl = np.concatenate(([0.0], v_cl, [0.0]))

        # Interpolate solver data onto Ghia points
        u_interp = np.interp(GHIA_Y, y_cl, u_cl)
        v_interp = np.interp(GHIA_X, x_cl, v_cl)

        err_u = float(np.max(np.abs(u_interp - GHIA_U)))
        err_v = float(np.max(np.abs(v_interp - GHIA_V)))

        logger.info(f"Maximum absolute error: U={err_u:.4e}, V={err_v:.4e}")
        logger.info(f"Tolerances: tol-u={args.tol_u:.3e}, tol-v={args.tol_v:.3e}")

        if err_u > args.tol_u or err_v > args.tol_v:
            logger.error("Validation failed: errors exceed tolerances.")
            sys.exit(2)

        logger.info("Validation successful.")

    finally:
        elapsed = time.perf_counter() - start_time
        logger.info(f"Total runtime: {elapsed:.2f} seconds")


if __name__ == "__main__":
    main()
